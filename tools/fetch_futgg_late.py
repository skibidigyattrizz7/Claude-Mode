#!/usr/bin/env python3
"""LATE real FC 27 base cards from FUT.GG -> 3d/js/meta/core/futplayers_late.js (GENERATED).

Why a second file: futplayers.js (tools/fetch_futgg_players.py) feeds seeded promo campaigns and the club-strength ranking, so adding
rows to it would reshuffle every promo card and move players between clubs (breaking saved clubs). These rows are only appended at
the very end of the card database (players.js `futLate`), after everything else, and are not promo candidates.

Collects (men, base gold/silver cards, one per person, through fut.gg's own JSON API, cached under tools/.futgg_players_cache, <= 2 req/s):
  * EVERY base card rated >= --min-ovr (default 72), and
  * the COMPLETE squads (every rating) of the top 5 leagues: Premier League, LALIGA, Bundesliga, Serie A, Ligue 1,
that is not already in futplayers.js and is not a hand-written real player. Stops immediately on a 403/429 (blocked).

  python3 tools/fetch_futgg_late.py [--min-ovr 72] [--game 27] [--asof YYYY-MM-DD]
Writes 3d/js/meta/core/futplayers_late.js and tools/futgg_late_report.json.
"""
import argparse, datetime, json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_futgg_players as F  # noqa: E402
from futgg_common import Client, ROOT  # noqa: E402

OUT_JS = os.path.join(ROOT, '3d', 'js', 'meta', 'core', 'futplayers_late.js')
OUT_REPORT = os.path.join(ROOT, 'tools', 'futgg_late_report.json')
TOP5 = {13: 'Premier League', 53: 'LALIGA', 19: 'Bundesliga', 31: 'Serie A', 16: 'Ligue 1'}


def existing_rows():
    rows = []
    for line in open(F.OUT_JS, encoding='utf-8'):
        m = re.match(r'^  (\[.*\]),?$', line.rstrip('\n'))
        if m:
            rows.append(json.loads(m.group(1)))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--min-ovr', type=int, default=72)
    ap.add_argument('--game', default='27')
    ap.add_argument('--asof', default=datetime.date.today().isoformat())
    a = ap.parse_args()
    F.PRIMARY[0] = a.game
    asof = datetime.date.fromisoformat(a.asof)
    client = Client()
    old = existing_rows()
    old_ids = {r[1] for r in old}
    taken = {r[0] for r in old}
    old_names = {(F.key(r[5]), r[7]) for r in old}
    hands = json.loads(subprocess.run(['node', os.path.join(ROOT, 'tools', 'list_hand_people.mjs')], check=True, capture_output=True, text=True, cwd=ROOT).stdout)
    taken |= {h['person'] for h in hands}

    items, seen = [], set()

    def add(batch):
        for it in batch:
            if it['eaId'] in seen or it.get('isHero') or it.get('isIcon') or card_kind(it) != 'b':
                continue
            seen.add(it['eaId'])
            items.append(it)

    card_kind = F.card_kind
    for ovr in range(99, a.min_ovr - 1, -1):
        add(F.all_pages(client, a.game, sorts='eaId', gender=1, rarity_id=F.BASE_RARITY, overall__gte=ovr, overall__lte=ovr))
        print(f'  ovr {ovr}: {len(items)} cards so far', file=sys.stderr, flush=True)
    for lid, name in TOP5.items():
        add(F.all_pages(client, a.game, sorts='eaId', gender=1, rarity_id=F.BASE_RARITY, league_id=lid))
        print(f'  {name}: {len(items)} cards so far', file=sys.stderr, flush=True)

    items = [it for it in items if (it.get('basePlayerEaId') or it['eaId']) not in old_ids and it['eaId'] not in old_ids]
    print(f'{len(items)} candidate cards not in futplayers.js; fetching definitions ...', file=sys.stderr)
    defs = F.definitions(client, a.game, [it['eaId'] for it in items])
    report = {'unmappedNations': {}, 'unusable': 0, 'handWritten': [], 'sameName': []}
    cards = []
    for it in items:
        d = defs.get(it['eaId'])
        c = F.parse_card(d, it, asof, 'b', a.game) if d else None
        if not c:
            report['unusable'] += 1
            continue
        if not c['nat']:
            report['unmappedNations'][c['natName']] = report['unmappedNations'].get(c['natName'], 0) + 1
            continue
        if any(F.match_score(h, c) >= 70 for h in hands if (h['pos'] == 'GK') == (c['pos'] == 'GK')):
            report['handWritten'].append(c['name'])  # a hand-written real player already is this person
            continue
        if (F.key(c['name']), c['nat']) in old_names:
            report['sameName'].append(c['name'])  # same name+nation as an existing row (e.g. their Icon): keep ids unambiguous
            continue
        cards.append(c)
    rows = []
    for c in sorted(cards, key=lambda c: (-c['ovr'], c['base'])):
        slug = F.make_slug(c, taken)
        taken.add(slug)
        rows.append(F.row_of(slug, c, True))
    head = f"""// GENERATED by tools/fetch_futgg_late.py -- do not edit by hand (re-run the tool instead).
// LATE real EA SPORTS FC {a.game} base cards from fut.gg (fan game, non-commercial). Fetched {datetime.date.today().isoformat()}.
// {len(rows)} cards: every base card rated {a.min_ovr}+ and the complete squads of the top 5 leagues that futplayers.js does not have.
// Same row format as futplayers.js. These are appended at the very END of the card database (players.js `futLate`) so no existing card,
// promo or saved club changes; they are not promo candidates and do not affect club strength ranking. Ids: rs_<slug>.
"""
    body = f"export const FUT_LATE_ROWS = [\n" + ',\n'.join('  ' + json.dumps(r, ensure_ascii=False, separators=(',', ':')) for r in rows) + '\n];\n'
    open(OUT_JS, 'w', encoding='utf-8').write(head + body)
    report['rows'] = len(rows)
    json.dump(report, open(OUT_REPORT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'done: {len(rows)} rows; {client.requests} requests, {client.hits} cache hits; skipped hand-written {len(report["handWritten"])}, '
          f'same-name {len(report["sameName"])}, unmapped nations {report["unmappedNations"]}', file=sys.stderr)


if __name__ == '__main__':
    main()
